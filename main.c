/* USER CODE BEGIN 0 */
void MAX30102_Task(void *argument)
{

    MAX30102_Data_t sensor;


    while(1)
    {

        MAX30102_ReadFIFO(&sensor.red,
                          &sensor.ir);



        sensor.bpm =
        MAX30102_EstimateBPM(sensor.ir);



        sensor.spo2 =
        MAX30102_EstimateSpO2(sensor.red,
                              sensor.ir);



        xQueueSend(LCDQueue,
                   &sensor,
                   portMAX_DELAY);



        vTaskDelay(pdMS_TO_TICKS(20));

    }
}

void vLCD_Task(void *argument)
{

    MAX30102_Data_t data;


    char line1[17];
    char line2[17];


    lcd_init();


    while(1)
    {


        if(xQueueReceive(LCDQueue,
                         &data,
                         portMAX_DELAY))
        {


            sprintf(line1,
                    "HR:%3ld BPM",
                    data.bpm);



            sprintf(line2,
                    "SpO2:%3ld%%",
                    data.spo2);



            lcd_write_byte(LCD_CMD,
                           LCD_CLEAR);



            lcd_puts(LCD_LINE1,
                     line1);


            lcd_puts(LCD_LINE2,
                     line2);

        }

    }

}

